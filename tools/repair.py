# -*- coding: utf-8 -*-
"""sainput 重复修复 —— 给 ASR 的重复循环兜个底。

为什么需要：zipformer 这类流式模型在小声、语速快、或句中切换语言时会在词尾打转，
输出「动动动荡荡荡」「为什么为什么」这种。换更强的模型能消掉绝大部分（实测
x-asr-480ms 在真机中文上重复数为 0），但模型永远可能偶发，这里做最后一道保险。

原则：**只动几乎不可能是正常中文的形态**。
正常叠字（看看 / 说说 / 刚刚 / 天天 / 妈妈 / 慢慢）和正常叠词（很多很多 / 一步一步 /
可以可以）一律不碰；英文的重复（ALWAYS ALWAYS）也不碰。
"""
import re

# 这些字连着出现两遍基本就是解码打转（正常中文里它们不叠字）
_NEVER_DOUBLE = set(
    "的了是在有和与也就都很别出来去么什这那他它们到为以被把让给向从而且或但还又再经过着吗呢吧"
    "连叠址识错操续问方"
)

# 笑声/语气词：连着多个是正常的，压到 2 个
_LAUGH = set("哈嘿呵嘻嗯哦")

# 称呼 / 叠词字:连着排多少个都**压不得**。
# 2026-10-31 体检 §3.4:旧的「中文 4 连以上压成一个」把 `妈妈妈妈` 吃成 `妈`、
# `谢谢谢谢` 吃成 `谢` —— 可这是孩子在叫人 / 连声道谢,不是解码打转。
# 单列一张表,不掺进 `_NEVER_DOUBLE`(那张表是「两连即算打转」的判据,语义不同)。
_KEEP_RUN = set("妈爸哥姐弟妹爷奶叔姨舅姑婆娃宝谢")

_CJK = re.compile(r"[\u4e00-\u9fff]")
_RE_ANY_RUN = re.compile(r"(.)\1+")         # 任意字符的连续段(统一在这里判,别拆成三条规则互相打架)
_RE_BLOCK3 = re.compile(r"(.{3,10}?)\1+")   # 3 字以上片段重复 2 次即算打转
_RE_BLOCK2 = re.compile(r"(.{2})\1{2,}")    # 2 字片段要重复 3 次以上才算


def _has_cjk(s):
    return bool(_CJK.search(s))


def _collapse_runs(t):
    """同一个字连排的处理。**只动中文**,拉丁字母/数字/标点一律不碰。

    为什么改(2026-10-30 用户实测报的「说重复的字会吞字」+ 2026-10-31 报的漏字):
    旧规则是 `(.)\\1{2,}` → 1,对**所有**字符生效,于是
      · `AAAA` → `A`、`saaaai` → `sai`、`1000000` → `10`(域名、型号、号码全被吃)
      · 「等等等 / 来来来 / 喂喂喂」这类**正常话**也被吃成 1 个字
    翻遍 125 个会话日志,真实出现过的 3 连**全是正常话**(等等等×25、喂喂喂×6、来来来×5),
    而模型打转是 4 连以上。所以现在:中文 **4 连以上**才压(笑声压到 2 个),
    **3 连保留**;拉丁/数字一个字都不动。
    """
    def f(m):
        ch = m.group(1)
        n = len(m.group(0))
        if not _CJK.match(ch):
            return m.group(0)              # 拉丁 / 数字 / 标点:绝不塌缩
        if ch in _KEEP_RUN:
            return m.group(0)              # 称呼/叠词(妈妈妈妈 / 谢谢谢谢):多少个都保留
        if n >= 4:
            return ch * (2 if ch in _LAUGH else 1)
        if n == 2 and ch in _NEVER_DOUBLE:
            return ch                      # 「识别别」「叠叠」这类:2 连即打转
        return m.group(0)                  # 2 连(正常叠字)与 3 连(等等等):保留
    return _RE_ANY_RUN.sub(f, t)


def repair(t):
    if not t:
        return t

    # 1) 同一个字连排:中文 4 连以上压掉,3 连保留,非中文不动(见 `_collapse_runs`)。
    t = _collapse_runs(t)

    # 2) 片段原样重复:3 字以上重复 2 次、2 字重复 3 次以上才压。
    #    只对含中文的片段生效 —— 「ALWAYS ALWAYS」「很多很多」这种正常内容不许动。
    #    整段都是称呼/叠词字的(`妈妈妈妈妈妈`)也不许动,见 `_KEEP_RUN`。
    def _block(m):
        seg = m.group(1)
        if not _has_cjk(seg):
            return m.group(0)
        if seg and all(c in _KEEP_RUN for c in seg):
            return m.group(0)
        return seg

    for rx in (_RE_BLOCK3, _RE_BLOCK2):
        for _ in range(4):
            nt = rx.sub(_block, t)
            if nt == t:
                break
            t = nt
    return t


